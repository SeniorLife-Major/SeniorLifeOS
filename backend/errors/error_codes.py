"""Domain and Application Error Codes.

Central enum providing machine-readable error codes for API error envelopes.
"""

from enum import Enum


class ErrorCode(str, Enum):
    # Common HTTP / System Errors
    BAD_REQUEST = "BAD_REQUEST"
    UNAUTHORIZED = "UNAUTHORIZED"
    FORBIDDEN = "FORBIDDEN"
    NOT_FOUND = "NOT_FOUND"
    CONFLICT = "CONFLICT"
    VALIDATION_FAILED = "VALIDATION_FAILED"
    INTERNAL_SERVER_ERROR = "INTERNAL_SERVER_ERROR"

    # Case & Workflow Domain Errors
    CASE_NOT_FOUND = "CASE_NOT_FOUND"
    CASE_VERSION_CONFLICT = "CASE_VERSION_CONFLICT"
    CASE_ALREADY_CLOSED = "CASE_ALREADY_CLOSED"
    WORKFLOW_EXECUTION_FAILED = "WORKFLOW_EXECUTION_FAILED"
    WORKFLOW_INVALID_STATE = "WORKFLOW_INVALID_STATE"

    # Document & Vault Domain Errors
    DOCUMENT_NOT_FOUND = "DOCUMENT_NOT_FOUND"
    DOCUMENT_INVALID_TYPE = "DOCUMENT_INVALID_TYPE"
    DOCUMENT_QUALITY_TOO_LOW = "DOCUMENT_QUALITY_TOO_LOW"
    DOCUMENT_EXTRACTION_FAILED = "DOCUMENT_EXTRACTION_FAILED"

    # Consent & Security Domain Errors
    CONSENT_DENIED = "CONSENT_DENIED"
    ACTOR_MISMATCH = "ACTOR_MISMATCH"
    SECRET_KEY_MISSING = "SECRET_KEY_MISSING"

    # Benefits Domain Errors
    SCHEME_NOT_FOUND = "SCHEME_NOT_FOUND"
    CRITERIA_EVALUATION_FAILED = "CRITERIA_EVALUATION_FAILED"

    # Task Domain Errors
    TASK_NOT_FOUND = "TASK_NOT_FOUND"
